class OrderPrintModel extends CommonModel
{
    // 自动验证设置
    protected $_validate = array();

    public function setPartner($orderId,$type,$partnerId)
    {
        $sql = "INSERT INTO ".$this->tablePrefix ."order_print (order_id,`type`,partner_id) VALUES";
        $sql .= "('{$orderId}','{$type}','{$partnerId}') ON DUPLICATE KEY UPDATE partner_id = '{$partnerId}'";
        return $this->execute($sql);
    }
}